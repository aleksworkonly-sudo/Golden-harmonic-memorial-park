'use strict';

// Optional browser QA using an installed Playwright module. Not part of the Node-only test script.
const assert=require('node:assert/strict');
const path=require('node:path');
const os=require('node:os');
const { chromium }=require(process.env.PAYMENT_PLAYWRIGHT_MODULE || 'playwright');
const { createPreviewServer }=require('./preview-server');

(async () => {
  const {server,state,submissions}=createPreviewServer();
  await new Promise((resolve) => server.listen(0,'127.0.0.1',resolve));
  const base=`http://127.0.0.1:${server.address().port}`;
  let browser;
  try {
    browser=await chromium.launch({channel:'msedge',headless:true});
    const context=await browser.newContext({viewport:{width:1365,height:1000}});
    const page=await context.newPage();
    const errors=[];page.on('pageerror',(error)=>errors.push(error.message));
    await page.goto(base+'/my-payments');
    await page.getByRole('button',{name:'Send verification link'}).waitFor();
    await page.getByLabel('Reservation reference').fill('PS-0001');
    await page.getByLabel('Registered email address').fill('buyer@example.test');
    await page.getByRole('button',{name:'Send verification link'}).click();
    await page.getByRole('status').filter({hasText:'If the details match'}).waitFor();
    assert.equal(state.requests,1);
    state.failNext=true;
    await page.getByRole('button',{name:'Send verification link'}).click();
    await page.getByRole('alert').waitFor();
    assert.equal(await page.getByRole('alert').evaluate((node)=>node===document.activeElement),true);
    assert.equal(await page.getByLabel('Registered email address').inputValue(),'buyer@example.test');
    await page.getByRole('button',{name:'Send verification link'}).click();
    await page.getByRole('status').filter({hasText:'If the details match'}).waitFor();
    const desktop=path.join(os.tmpdir(),'gh-payment-cp2-desktop.png');
    await page.screenshot({path:desktop,fullPage:true});
    await page.getByRole('button',{name:'Account login',exact:true}).click();
    await page.getByLabel('Account email').fill('buyer@example.test');
    await page.getByLabel('Password',{exact:true}).fill('demo-password');
    await page.getByRole('button',{name:'Sign in',exact:true}).click();
    await page.getByRole('heading',{name:'Choose your account'}).waitFor();
    await page.getByRole('button',{name:/Regular plot/}).click();
    await page.getByRole('heading',{name:'Recorded payment history'}).waitFor();
    await page.getByRole('button',{name:'Add payment proof'}).click();
    await page.getByLabel('Receipt image',{exact:true}).setInputFiles({name:'bad.txt',mimeType:'text/plain',buffer:Buffer.from('not a receipt')});
    await page.getByRole('alert').filter({hasText:'Choose a JPG'}).waitFor();
    assert.equal(await page.getByRole('alert').evaluate((node)=>node===document.activeElement),true);
    await page.getByLabel('Amount you transferred').fill('4900');
    await page.getByLabel('Transfer reference',{exact:true}).fill('BROWSER-001');
    await page.getByLabel('Transfer date').fill('2026-10-30');
    const image=Buffer.from((await submissions.command()).image,'base64');
    await page.getByLabel('Receipt image',{exact:true}).setInputFiles({name:'receipt.png',mimeType:'image/png',buffer:image});
    await page.getByRole('button',{name:'Review submission',exact:true}).click();
    await page.getByRole('heading',{name:'Review before submitting'}).waitFor();
    await page.getByText('Your amount differs from the expected amount.',{exact:false}).waitFor();
    const cp3desktop=path.join(os.tmpdir(),'gh-payment-cp3-desktop.png');
    await page.screenshot({path:cp3desktop,fullPage:true});
    for(const width of [320,390,768]) {
      await page.setViewportSize({width,height:900});
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`proof review overflows at ${width}px`);
    }
    const cp3mobile=path.join(os.tmpdir(),'gh-payment-cp3-mobile.png');
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:cp3mobile,fullPage:true});
    state.loseNextSubmission=true;
    await page.getByRole('button',{name:'Confirm and submit proof'}).click();
    await page.getByRole('button',{name:'Check / retry submission'}).waitFor();
    assert.equal(submissions.db.count('paymentProofs'),1);
    await page.getByRole('button',{name:'Check / retry submission'}).click();
    await page.getByRole('status').filter({hasText:'saved. Awaiting verification'}).waitFor();
    await page.getByRole('button',{name:'Correct submission',exact:true}).waitFor();
    assert.equal(submissions.db.count('paymentProofs'),1);
    await page.getByRole('button',{name:'View proof',exact:true}).click();
    await page.getByRole('img',{name:'Saved private proof',exact:true}).waitFor();
    await page.getByRole('button',{name:'Correct submission',exact:true}).click();
    assert.equal(await page.getByLabel('Transfer reference',{exact:true}).inputValue(),'BROWSER-001');
    await page.getByLabel('Transfer reference',{exact:true}).fill('BROWSER-002');
    await page.getByLabel('Receipt image',{exact:true}).setInputFiles({name:'receipt.png',mimeType:'image/png',buffer:image});
    await page.getByRole('button',{name:'Review submission',exact:true}).click();
    await page.getByRole('button',{name:'Confirm and submit proof'}).click();
    await page.getByText(/BROWSER-002 · 2026-10-30 · Revision 2/).waitFor();
    await page.getByText('Earlier proof revisions',{exact:true}).click();
    await page.getByRole('button',{name:'View revision 1',exact:true}).click();
    await page.getByRole('img',{name:'Saved private proof',exact:true}).waitFor();
    assert.equal(submissions.db.count('paymentProofs'),2);
    assert.equal((await submissions.core.list(submissions.account)).cases.length,1);
    assert.equal(submissions.db.count('ledgerEntries'),0);
    await page.setViewportSize({width:1365,height:1000});
    assert.equal(await page.locator('tbody tr').count(),20);
    await page.getByRole('button',{name:'Load earlier payments'}).click();
    await page.waitForFunction(()=>document.querySelectorAll('tbody tr').length===24);
    await page.getByRole('button',{name:'Choose another account'}).click();
    await page.getByRole('button',{name:/Premium plot/}).click();
    await page.getByRole('heading',{name:'Recorded payment history'}).waitFor();
    await page.getByText('No online proof submissions yet.').waitFor();
    await page.getByRole('button',{name:'Close payment history'}).click();
    await page.getByRole('button',{name:'Sign in',exact:true}).waitFor();
    await page.goto(base+'/payment-link.html#access='+'a'.repeat(43));
    await page.getByRole('button',{name:'Continue securely'}).waitFor();
    assert.equal(new URL(page.url()).hash,'');
    assert.equal(state.exchanges,0);
    await page.getByRole('button',{name:'Continue securely'}).click();
    await page.getByRole('heading',{name:'Recorded payment history'}).waitFor();
    assert.equal(state.exchanges,1);
    await page.getByRole('button',{name:'Add payment proof'}).click();
    await page.getByLabel('Amount you transferred').fill('5000');
    await page.getByLabel('Transfer reference',{exact:true}).fill('GUEST-001');
    await page.getByLabel('Transfer date').fill('2026-10-30');
    await page.getByLabel('Receipt image',{exact:true}).setInputFiles({name:'receipt.png',mimeType:'image/png',buffer:image});
    await page.getByRole('button',{name:'Review submission',exact:true}).click();
    await page.getByRole('button',{name:'Confirm and submit proof'}).click();
    await page.getByText(/GUEST-001 · 2026-10-30 · Revision 1/).waitFor();
    assert.equal((await submissions.core.list(submissions.guest)).cases.length,1);
    for(const width of [320,390,768]) {
      await page.setViewportSize({width,height:900});
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`page overflows at ${width}px`);
    }
    await page.setViewportSize({width:390,height:844});
    const mobile=path.join(os.tmpdir(),'gh-payment-cp2-mobile.png');
    await page.screenshot({path:mobile,fullPage:true});
    state.accessLost=true;
    await page.getByRole('button',{name:'Refresh submissions',exact:true}).click();
    await page.getByRole('button',{name:'Send verification link'}).waitFor();
    assert.equal(await page.getByRole('heading',{name:'Recorded payment history'}).count(),0);
    state.accessLost=false;
    await page.goto(base+'/payment-link.html');
    assert.equal(await page.getByRole('button',{name:'Continue securely'}).isDisabled(),true);
    state.enabled=false;
    await page.goto(base+'/my-payments');
    await page.getByRole('heading',{name:'Please contact the office'}).waitFor();
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({passed:true,checks:'CP2 regression; CP3 account/guest upload, image rejection, review/mismatch, uncertain retry, proof privacy, correction history, no posting, 320/390/768px overflow, console errors',desktop,mobile,cp3desktop,cp3mobile},null,2));
  } finally {
    if(browser) await browser.close();
    await new Promise((resolve)=>server.close(resolve));
  }
})().catch((error)=>{console.error(error);process.exitCode=1;});
